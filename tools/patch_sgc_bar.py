#!/usr/bin/env python3
"""Apply the Stargate Command skin to a clone of omarchy.bar's Bar.qml.

The SGC bar is the stock bar plus a dialing-computer look: cut-corner panels
framed in event-horizon blue with amber labels, workspaces as gate chevrons,
a mini stargate in the left cap and a gate-status readout docked left of the
clock. The readout and the mini gate follow the wallpaper loop through mpv's
IPC socket (see GateTimeline.js, generated by gen_gate_js.py).

Usage: patch_sgc_bar.py PLUGIN_DIR
  PLUGIN_DIR holds a fresh copy of /usr/share/omarchy/shell/plugins/bar;
  Bar.qml and manifest.json are rewritten in place.
"""
import json
import os
import sys

DIR = sys.argv[1]
QML = os.path.join(DIR, "Bar.qml")
src = open(QML).read()


def sub(old, new, count=1):
    global src
    n = src.count(old)
    if n != count:
        sys.exit("patch_sgc_bar: expected %d match(es), found %d for:\n%s" % (count, n, old))
    src = src.replace(old, new)


